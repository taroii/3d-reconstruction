r"""
Paper figures and tables, generated from result files — never hand-edited.

Every number the paper prints comes from a file written by `estimator_diag.py`
or `evaluate.py`. Nothing here recomputes a metric: if a figure and a table
disagree, that is a bug in one of them, not a judgement call. The ACCV draft
had hand-transcribed numbers in its tables, which is how a claim survived in
the text after the code behind it had changed.

Subcommands:
  table_results   runs/*/eval.csv  -> results_table.tex
  fig_diagnostic  diag.json        -> fig_diagnostic.pdf
  table_diagnostic diag.json       -> diagnostic_table.tex

Usage:
  python src/figures.py table_results  --eval results/eval.csv --out paper/figures
  python src/figures.py fig_diagnostic --diag results/estimator_diag/diag.json \
                                       --out paper/figures
"""
import argparse
import csv
import json
import os

import numpy as np

# Arm order and display names. Fixed here so every table and figure in the
# paper lists the arms in the same order, whatever order the CSV rows happen
# to be in.
ARMS = [
    ("base",               r"VGGT (pretrained)"),
    ("none:clamp:0",       r"Baseline ($\lambda=0$)"),
    ("umbrella:clamp:1",   r"Umbrella, clamp"),
    ("umbrella:unitmean:1", r"Umbrella, unit-mean"),
    ("umbrella:binary:1",  r"Umbrella, binary"),
    ("grad:clamp:1",       r"Gradient control"),
    ("cotangent:clamp:1",  r"Cotangent (true curvature)"),
]
DATASETS = [("ibims1", "iBims-1"), ("nyuv2", "NYUv2"), ("bonn", "Bonn")]
REGIONS = [("all", "all"), ("edge", "edge"), ("interior", "interior")]


def _read_eval(path):
    """Eval rows, with incomplete runs refused rather than averaged in.

    `complete=0` means the checkpoint was a mid-run periodic save (see
    train.py). Those must never reach a table: they look like finished arms in
    every other column.
    """
    rows = list(csv.DictReader(open(path)))
    if not rows:
        raise SystemExit(f"{path} has no rows")
    bad = [r for r in rows if r.get("complete", "1") != "1"]
    if bad:
        names = sorted({f"{r['arm']}/seed{r['seed']}" for r in bad})
        raise SystemExit(
            f"refusing to tabulate {len(bad)} rows from incomplete runs: "
            f"{names}. Re-run them or drop them explicitly.")
    for r in rows:
        for k in ("absrel", "delta1"):
            r[k] = float(r[k])
        r["seed"] = int(r["seed"])
    return rows


def _cell(rows, arm, ds, region, metric):
    """mean +- std over seeds, or None when the arm was not run."""
    v = [r[metric] for r in rows
         if r["arm"] == arm and r["dataset"] == ds and r["region"] == region]
    if not v:
        return None
    return float(np.mean(v)), (float(np.std(v, ddof=1)) if len(v) > 1 else 0.0), len(v)


def table_results(a):
    rows = _read_eval(a.eval)
    present = [(k, n) for k, n in ARMS
               if any(r["arm"] == k for r in rows)]
    missing = [k for k, _ in ARMS if k not in {p[0] for p in present}]

    metric = a.metric
    lines = [
        r"% generated by src/figures.py table_results -- do not edit",
        r"\begin{tabular}{l" + "r" * (len(DATASETS) * len(REGIONS)) + "}",
        r"\toprule",
        "".join([r"&\multicolumn{3}{c}{%s}" % n for _, n in DATASETS]) + r"\\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
        "Arm" + "".join([f"&{rn}" for _ in DATASETS for _, rn in REGIONS]) + r"\\",
        r"\midrule",
    ]
    for key, name in present:
        cells = []
        for ds, _ in DATASETS:
            for region, _ in REGIONS:
                c = _cell(rows, key, ds, region, metric)
                if c is None:
                    cells.append("--")
                elif c[2] > 1:
                    cells.append(f"{c[0]:.4f}\\,\\tiny{{$\\pm${c[1]:.4f}}}")
                else:
                    cells.append(f"{c[0]:.4f}")
        lines.append(f"{name}&" + "&".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    os.makedirs(a.out, exist_ok=True)
    p = os.path.join(a.out, "results_table.tex")
    open(p, "w").write("\n".join(lines) + "\n")
    print(f"wrote {p}  ({len(present)} arms, metric={metric})")
    if missing:
        print(f"  NOT YET RUN: {', '.join(missing)}")
    seeds = sorted({r['seed'] for r in rows if r['arm'] != 'base'})
    print(f"  seeds present: {seeds or 'none (base only)'}")


def _diag(path, analysis):
    rows = [r for r in json.load(open(path)) if r["analysis"] == analysis]
    if not rows:
        raise SystemExit(f"{path} has no '{analysis}' rows -- "
                         f"run estimator_diag.py --analysis all --out ...")
    return rows


def fig_diagnostic(a):
    """The claim the reviewers' objection turns on, in two panels.

    Left: the signal on ONE sphere of fixed curvature, as the sphere is moved
    away from the camera. A curvature estimator is flat here by definition;
    anything that rises is reporting depth. Right: what fraction of pixels on a
    pure depth discontinuity -- zero curvature, two flat planes -- the signal
    puts in its top decile.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    sweep, edges = _diag(a.diag, "depthsweep"), _diag(a.diag, "edges")
    ests = ["umbrella", "cotangent", "grad", "spacing"]
    style = {"umbrella": ("C3", "o", "umbrella Laplacian (ours, ACCV)"),
             "cotangent": ("C0", "s", "cotangent/Voronoi (true $|H|$)"),
             "grad": ("C2", "^", "first-order control"),
             "spacing": ("C7", "v", "vertex spacing")}

    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(9.0, 3.4))

    for est in ests:
        pts = sorted([(r["dist"], r["drift_vs_3m"]) for r in sweep
                      if r["estimator"] == est])
        if not pts:
            continue
        c, m, lab = style[est]
        ax0.plot([p[0] for p in pts], [p[1] for p in pts],
                 marker=m, color=c, label=lab, lw=1.6, ms=5)
    ax0.axhline(1.0, color="k", ls=":", lw=1.0)
    ax0.set_xlabel("sphere distance (m)")
    ax0.set_ylabel("median signal, relative to 3 m")
    ax0.set_title("One sphere, fixed curvature, moved away", fontsize=9)
    ax0.legend(fontsize=7, frameon=False)

    labels, vals, cols, caps = [], [], [], []
    for est in ests:
        r = [x for x in edges if x["estimator"] == est]
        if not r:
            continue
        labels.append(est)
        vals.append(r[0]["rate_step"])
        cols.append(style[est][0])
        caps.append(r[0].get("structural_cap", 1.0))
    # A one-sided stencil -- which is what the published gradient control uses
    # -- can only fire on one of the two columns of a step, so its rate is
    # capped at 0.5 by its own arithmetic. Drawn unmarked beside an uncapped
    # 1.00 it would read as "catches half of them", which is not what it means.
    ax1.bar(range(len(vals)), vals, color=cols, width=0.6,
            hatch=["//" if c < 1.0 else "" for c in caps],
            edgecolor="white", linewidth=0)
    for i, c in enumerate(caps):
        if c < 1.0:
            ax1.plot([i - 0.3, i + 0.3], [c, c], color="k", ls="--", lw=1.0)
            ax1.text(i, c + 0.12, f"capped at {c:.1f}\nby the stencil",
                     ha="center", fontsize=6, style="italic")
    ax1.set_xticks(range(len(labels)))
    ax1.set_xticklabels(labels, fontsize=8)
    ax1.set_ylabel("fraction in top decile")
    ax1.set_ylim(0, 1.05)
    ax1.set_title("Pixels on a zero-curvature depth step", fontsize=9)
    for i, v in enumerate(vals):
        ax1.text(i, v + 0.03, f"{v:.2f}", ha="center", fontsize=8)

    for ax in (ax0, ax1):
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    os.makedirs(a.out, exist_ok=True)
    p = os.path.join(a.out, "fig_diagnostic.pdf")
    fig.savefig(p, bbox_inches="tight")
    fig.savefig(p.replace(".pdf", ".png"), dpi=200, bbox_inches="tight")
    print(f"wrote {p} (+ .png)")


def table_diagnostic(a):
    """The diagnostic's headline numbers, with each one's prediction beside it."""
    depth = _diag(a.diag, "depth")
    sweep = _diag(a.diag, "depthsweep")
    edges = _diag(a.diag, "edges")
    ests = ["umbrella", "cotangent", "grad", "spacing"]

    far = {r["estimator"]: r["far_over_near"] for r in depth}
    drift = {r["estimator"]: r["drift_vs_3m"] for r in sweep if r["dist"] == 12.0}
    step = {r["estimator"]: r["rate_step"] for r in edges}

    lines = [
        r"% generated by src/figures.py table_diagnostic -- do not edit",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Estimator&two spheres&one sphere&depth step\\",
        r"&$3\to9$\,m, same image&$3\to12$\,m, across images&top-decile rate\\",
        r"\midrule",
    ]
    for e in ests:
        if e not in far:
            continue
        lines.append(f"{e}&{far[e]:.2f}$\\times$&{drift.get(e, float('nan')):.2f}"
                     f"$\\times$&{step.get(e, float('nan')):.2f}" + r"\\")
    lines += [
        r"\midrule",
        r"\emph{curvature predicts}&1.00$\times$&1.00$\times$&0.00\\",
        r"\emph{$Z^2$, $Z$ predict}&9.00$\times$&4.00$\times$&--\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    os.makedirs(a.out, exist_ok=True)
    p = os.path.join(a.out, "diagnostic_table.tex")
    open(p, "w").write("\n".join(lines) + "\n")
    print(f"wrote {p}")


def _selftest():
    import tempfile
    d = tempfile.mkdtemp()

    # -- an incomplete run must be refused, not silently averaged -----------
    p = os.path.join(d, "bad.csv")
    with open(p, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["arm", "seed", "step", "complete",
                                          "dataset", "region", "absrel", "delta1"])
        w.writeheader()
        w.writerow(dict(arm="none:clamp:0", seed=0, step=500, complete=0,
                        dataset="ibims1", region="all", absrel=0.04, delta1=0.9))
    try:
        _read_eval(p)
    except SystemExit as e:
        assert "incomplete" in str(e), str(e)
    else:
        raise AssertionError("an incomplete run was tabulated")

    # -- mean/std over seeds, and a one-seed arm carries no fake spread -----
    p = os.path.join(d, "ok.csv")
    with open(p, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["arm", "seed", "step", "complete",
                                          "dataset", "region", "absrel", "delta1"])
        w.writeheader()
        for s, v in ((0, 0.040), (1, 0.050)):
            w.writerow(dict(arm="none:clamp:0", seed=s, step=6000, complete=1,
                            dataset="ibims1", region="all", absrel=v, delta1=0.9))
        w.writerow(dict(arm="base", seed=-1, step=0, complete=1,
                        dataset="ibims1", region="all", absrel=0.042, delta1=0.9))
    rows = _read_eval(p)
    m, sd, n = _cell(rows, "none:clamp:0", "ibims1", "all", "absrel")
    assert abs(m - 0.045) < 1e-9 and n == 2, (m, n)
    assert abs(sd - np.std([0.040, 0.050], ddof=1)) < 1e-12, sd
    m1, sd1, n1 = _cell(rows, "base", "ibims1", "all", "absrel")
    assert n1 == 1 and sd1 == 0.0, (n1, sd1)
    assert _cell(rows, "cotangent:clamp:1", "ibims1", "all", "absrel") is None, \
        "an arm with no rows must report missing, not zero"

    # -- a table must not invent arms it has no data for --------------------
    class A:
        pass
    a = A(); a.eval = p; a.out = d; a.metric = "absrel"
    table_results(a)
    tex = open(os.path.join(d, "results_table.tex")).read()
    assert "Cotangent" not in tex, "table lists an arm that was never run"
    assert "Baseline" in tex and "pretrained" in tex
    assert tex.count(r"\\") >= 4
    print("selftest: figures ok")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", default="selftest",
                    choices=["table_results", "fig_diagnostic",
                             "table_diagnostic", "selftest"])
    ap.add_argument("--eval", default="results/eval.csv")
    ap.add_argument("--diag", default="results/estimator_diag/diag.json")
    ap.add_argument("--out", default="paper/figures")
    ap.add_argument("--metric", default="absrel", choices=["absrel", "delta1"])
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest or a.cmd == "selftest":
        _selftest()
        return
    {"table_results": table_results,
     "fig_diagnostic": fig_diagnostic,
     "table_diagnostic": table_diagnostic}[a.cmd](a)


if __name__ == "__main__":
    main()
